// One installable release for this app. The interface installs; media downloads only on request.
// Run after changing any app or media file: node scripts/build-pwa.cjs (or --check).
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const ROOT=path.resolve(__dirname,'..'),MODULE='voc';
const sha=(body,encoding='hex')=>crypto.createHash('sha256').update(body).digest(encoding);
const SKIP=new Set(['node_modules','tests','scripts','docs','.git','.github','_site']);
function walk(directory){
 return fs.readdirSync(path.join(ROOT,directory),{withFileTypes:true}).flatMap(entry=>{
  if(SKIP.has(entry.name)||entry.name.startsWith('.'))return [];
  const file=directory?directory+'/'+entry.name:entry.name;
  return entry.isDirectory()?walk(file):[file];
 });
}
function mediaFiles(){
 if(MODULE==='voc'){
  const files=[];
  for(let category=1;category<=40;category++)for(const [kind,ext]of [['images','webp'],['sounds','m4a']])
   files.push(...fs.readdirSync(path.join(ROOT,kind,String(category))).filter(name=>new RegExp(`^\\d+\\.${ext}$`).test(name)).sort().map(name=>`${kind}/${category}/${name}`));
  return files;
 }
 if(MODULE==='senb')return [...walk('images'),...walk('sounds')].filter(file=>/\.(webp|png|m4a)$/.test(file)).sort();
 const used=new Set(),{words}=JSON.parse(fs.readFileSync(path.join(ROOT,'assets/words.json')));
 for(const word of words)for(const asset of [word.image,word.audio,...word.syllableAudio]){
  if(asset.library!=='taffaha'||!/^assets\/(images|sounds)\//.test(asset.path)||asset.path.split('/').includes('..'))throw Error('Invalid media: '+asset.path);
  if(fs.existsSync(path.join(ROOT,asset.path)))used.add(asset.path);
  else if(asset===word.image||asset===word.audio)throw Error('Missing media: '+asset.path);
 }
 return [...used].sort();
}
function createRelease(){
 const media=mediaFiles().map(url=>{const body=fs.readFileSync(path.join(ROOT,url));return {module:MODULE,url,bytes:body.length,revision:sha(body)};});
 media.sort((a,b)=>a.url.localeCompare(b.url));
 const shell=walk('').filter(file=>{
  if(/^(images|sounds)\//.test(file))return MODULE==='voc'&&/^(images\/41\/|images\/(logo\.webp|placeholder\.svg)$)/.test(file);
  if(/^assets\/(images|sounds)\//.test(file))return false;
  return /\.(html|css|js|svg|json|png|webp|woff2|txt|webmanifest)$/.test(file)&&!['package.json','package-lock.json','sw.js','assets/pwa-release.js','manifest.json'].includes(file);
 }).sort();
 if(!shell.includes('index.html')||!shell.includes('manifest.webmanifest'))throw Error('Shell must include index.html and manifest.webmanifest');
 const integrity=Object.fromEntries(shell.map(file=>[file,'sha256-'+sha(fs.readFileSync(path.join(ROOT,file)),'base64')]));
 const version=sha(JSON.stringify({integrity,media,worker:sha(fs.readFileSync(path.join(ROOT,'sw.js')))})).slice(0,20);
 return {version,shell,integrity,media};
}
function build({check=false}={}){
 if(!check&&MODULE==='voc')require('./build-game-data.cjs');
 if(MODULE==='senb'){
  // Retained for the sentence media model and tooling; downloads use the release inventory.
  const assets=mediaFiles().map(file=>{const body=fs.readFileSync(path.join(ROOT,file));return {url:file,bytes:body.length,revision:sha(body)};});
  const catalog=JSON.stringify({version:sha(JSON.stringify(assets)).slice(0,20),totalBytes:assets.reduce((sum,a)=>sum+a.bytes,0),assets});
  const catalogPath=path.join(ROOT,'assets/offline-assets.json');
  if(check){if(fs.readFileSync(catalogPath,'utf8')!==catalog)throw Error('Sentence media catalog is stale');}else fs.writeFileSync(catalogPath,catalog);
 }
 const release=createRelease(),output='// Generated by scripts/build-pwa.cjs.\nself.APP_RELEASE='+JSON.stringify(release)+';\n',target=path.join(ROOT,'assets/pwa-release.js');
 if(check){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output)throw Error('Release is stale; run node scripts/build-pwa.cjs');}else fs.writeFileSync(target,output);
 console.log(`${MODULE} ${release.version}: ${release.shell.length} shell files; ${release.media.length} media files (${(release.media.reduce((sum,a)=>sum+a.bytes,0)/1e6).toFixed(1)} MB).`);
 return release;
}
if(require.main===module)build({check:process.argv.includes('--check')});
module.exports={build,createRelease};
